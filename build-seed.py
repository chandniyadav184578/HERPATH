#!/usr/bin/env python3
"""Bundles data/sample-*.json into data/seed-data.js so the site works from file:// (browsers block fetch() of local JSON).
Run after editing any data/sample-*.json:  python3 tools/build-seed.py"""
import json,pathlib
d=pathlib.Path(__file__).resolve().parent.parent/'data'
seed={}
for k,f in [('symptoms','sample-symptoms'),('appointments','sample-appointments'),('notifications','sample-notifications'),('profile','sample-profile')]:
    o=json.loads((d/(f+'.json')).read_text(encoding='utf-8')); o.pop('_about',None); seed[k]=o
(d/'seed-data.js').write_text('/* Generated by tools/build-seed.py from data/sample-*.json. Do not edit by hand. */\nwindow.HERPATH_SEED='+json.dumps(seed,ensure_ascii=False)+';\n',encoding='utf-8')
print('seed-data.js written:',len(seed['symptoms']['entries']),'entries')
